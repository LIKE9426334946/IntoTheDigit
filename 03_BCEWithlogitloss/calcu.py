import torch

x = torch.tensor([[4.1885, 2.1488, 1.7239], [1.2623, 2.2902, 1.0140], [3.1483, 1.5639, 3.3146]])
y = torch.sigmoid(x)
print(y)
"""
tensor([[0.9851, 0.8956, 0.8486],
        [0.7794, 0.9081, 0.7338],
        [0.9588, 0.8269, 0.9649]])
target对应为0的元素有5个，对应为1的元素有4个
"""

# 以下为target为0对应的损失函数
x1 = torch.tensor([0.9851, 0.8956, 0.8486, 0.7794, 0.8269])
y1 = -torch.log(1 - x1)  # 得到的损失函数
print(y1)
# tensor([4.2064, 2.2595, 1.8878, 1.5114, 1.7539])


# 以下为target为1对应的损失函数
x2 = torch.tensor([0.9081, 0.7338, 0.9588, 0.9649])
y2 = -torch.log(x2)
print(y2)
# tensor([0.0964, 0.3095, 0.0421, 0.0357])

y3 = torch.cat([y1, y2])
print(y3.sum() / 9)
# 结果为1.3448
